import { chromium } from 'playwright';
const url=process.env.PWA_URL;
if(!url) throw new Error('PWA_URL missing');
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true,userAgent:'Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) AppleWebKit/605.1.15 Version/18.0 Mobile/15E148 Safari/604.1'});
const page=await context.newPage();
await page.goto(url,{waitUntil:'domcontentloaded',timeout:30000});
await page.locator('#authScreen:not([hidden])').waitFor();
const optionCount=await page.locator('#skuSelect option').count();
if(optionCount!==0) throw new Error(`Public locked page exposed ${optionCount} options`);
const body=await page.locator('body').innerText();
if(body.includes('声光漏水报警器')||body.includes('手动抽芯铆钉枪')) throw new Error('Public locked page leaked SKU names');
const html=await page.content();
if(html.includes('声光漏水报警器')||html.includes('手动抽芯铆钉枪')) throw new Error('Public HTML leaked SKU plaintext');
await page.fill('#authPassword','definitely-wrong');await page.click('#loginBtn');await page.waitForTimeout(400);
const err=await page.locator('#authError').innerText();
if(!err.includes('密码错误')) throw new Error('Wrong password not rejected publicly');
await page.evaluate(()=>navigator.serviceWorker.ready);
await page.screenshot({path:'auth-public-login.png',fullPage:true});
console.log(JSON.stringify({optionCount,wrongPasswordRejected:true,serviceWorkerReady:true},null,2));
await browser.close();
